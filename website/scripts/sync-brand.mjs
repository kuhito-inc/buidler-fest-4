import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const source = resolve(root, "brand/logos/builder-fest-2027-logo.png");
const target = resolve(root, "website/public/brand/logo.png");
const expectedGitBlobSha = "13207b122d312f7982e5ff843b49a87e14c00993";
if (!existsSync(source)) throw new Error("Approved logo master missing: " + source);
const bytes = readFileSync(source);
const hash = createHash("sha1").update(Buffer.from("blob " + bytes.length + "\0")).update(bytes).digest("hex");
if (hash !== expectedGitBlobSha) throw new Error("Approved logo master changed! Expected " + expectedGitBlobSha + " but got " + hash);
mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, bytes);
console.log("Approved logo copied byte-for-byte; Git blob SHA verified:", hash);
